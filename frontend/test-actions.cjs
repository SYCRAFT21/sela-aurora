const assert = require('node:assert/strict');
const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/brave-browser', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const calls = [];
  let failReload = false;
  const account = { id: 'google-account', email: 'me@example.test', provider: 'google', reconnect: false, gmail_modify: true };
  const mail = { id: 'mail-1', account_id: account.id, recipient: 'Friend <friend@example.test>', sender: 'Me <me@example.test>', subject: 'Sent message', snippet: '', received: '2026-11-06T10:00:00Z', unread: false, url: '' };
  try {
    await page.route('**/api/**', async route => {
      const url = new URL(route.request().url());
      if (url.pathname === '/api/accounts') return route.fulfill({ json: [account] });
      if (url.pathname.startsWith('/api/inbox/')) return failReload ? route.fulfill({ status: 503, body: 'synthetic refresh failure' }) : route.fulfill({ json: { messages: [mail], errors: [], next_cursors: {}, limited_accounts: [] } });
      if (url.pathname.endsWith('/action')) { calls.push(route.request().postDataJSON()); return route.fulfill({ status: 204 }); }
      if (url.pathname.startsWith('/api/message/')) return route.fulfill({ json: { sender: mail.sender, recipient: mail.recipient, subject: mail.subject, received: mail.received, body: 'Sent body', url: '' } });
      throw Error('Unexpected API call: ' + url.pathname);
    });
    await page.goto('http://127.0.0.1:4175');
    await page.locator('.au-mail-row').first().click();
    failReload = true;
    await page.getByTitle('Beri bintang').click();
    assert.deepEqual(calls[0], { id: 'mail-1', action: 'star' });
    await page.getByText('Gagal memuat email', { exact: false }).waitFor();
    assert.equal(await page.getByText('Perubahan pesan tersimpan di Gmail').count(), 0);
    failReload = false;
    await page.getByTitle('Sinkronkan').last().click();
    await page.locator('.au-mail-row').first().click();
    await page.getByTitle('Arsipkan pesan').click();
    assert.deepEqual(calls[1], { id: 'mail-1', action: 'archive' });
    await page.reload();
    await page.locator('.au-mail-row').first().click();
    assert.equal(await page.getByTitle('Beri bintang').count(), 1);
    const composePage = await browser.newPage();
    const composeCalls = [];
    await composePage.route('**/api/**', route => {
      const url = new URL(route.request().url());
      if (url.pathname === '/api/accounts') return route.fulfill({ json: [account] });
      if (url.pathname.startsWith('/api/inbox/')) return route.fulfill({ json: { messages: [mail], errors: [], next_cursors: {}, limited_accounts: [] } });
      if (url.pathname === '/api/compose/google-account') { composeCalls.push(route.request().postDataJSON()); return route.fulfill({ json: { id: 'fictional-id' }, status: 201 }); }
      if (url.pathname.startsWith('/api/message/')) return route.fulfill({ json: { sender: mail.sender, recipient: mail.recipient, subject: mail.subject, received: mail.received, body: 'Sent body', url: '' } });
      throw Error('Unexpected API call: ' + url.pathname);
    });
    await composePage.goto('http://127.0.0.1:4175');
    await composePage.getByRole('button', { name: /Tulis email/ }).click();
    await composePage.getByRole('textbox', { name: 'Kepada', exact: true }).fill('friend@example.test');
    await composePage.getByRole('textbox', { name: 'Subjek', exact: true }).fill('Hello');
    await composePage.getByRole('button', { name: 'CC', exact: true }).click();
    await composePage.getByRole('textbox', { name: 'CC', exact: true }).fill('team@example.test');
    await composePage.getByRole('button', { name: 'BCC', exact: true }).click();
    await composePage.getByRole('textbox', { name: 'BCC', exact: true }).fill('secret@example.test');
    await composePage.locator('.au-compose-body').fill('Body text');
    await composePage.getByRole('button', { name: 'Simpan draf' }).click();
    assert.deepEqual(composeCalls[0], { to: 'friend@example.test', cc: 'team@example.test', bcc: 'secret@example.test', subject: 'Hello', body: 'Body text', mode: 'draft' });
    await composePage.locator('.au-mail-row').first().click();
    await composePage.getByRole('button', { name: /Balas/ }).first().click();
    await composePage.getByRole('button', { name: 'Simpan draf' }).click();
    assert.deepEqual(composeCalls[1], { to: 'friend@example.test', subject: 'Re: Sent message', body: '', mode: 'draft', message_id: 'mail-1', draft_reply: true });
    await composePage.locator('.au-mail-row').first().click();
    await composePage.getByRole('button', { name: /Balas/ }).first().click();
    assert.equal(await composePage.getByRole('textbox', { name: 'Kepada', exact: true }).inputValue(), 'friend@example.test');
    await composePage.locator('.au-compose-body').fill('Reply body');
    composePage.once('dialog', dialog => dialog.accept());
    const replyResponse = composePage.waitForResponse('**/api/compose/google-account');
    await composePage.getByRole('button', { name: 'Kirim', exact: true }).click();
    await replyResponse;
    assert.deepEqual({ ...composeCalls[2], submission_id: undefined }, { to: 'friend@example.test', subject: 'Re: Sent message', body: 'Reply body', mode: 'reply', message_id: 'mail-1', submission_id: undefined });
    assert.match(composeCalls[2].submission_id, /^[0-9a-f-]{36}$/);
    await composePage.locator('.au-mail-row').first().click();
    await composePage.getByRole('button', { name: 'Balas semua' }).click();
    assert.equal(await composePage.getByRole('textbox', { name: 'Kepada', exact: true }).inputValue(), 'friend@example.test');
    assert.equal(await composePage.getByRole('textbox', { name: 'CC', exact: true }).inputValue(), '');
    await composePage.getByRole('textbox', { name: 'Kepada', exact: true }).fill('');
    await composePage.getByRole('textbox', { name: 'Subjek', exact: true }).fill('');
    await composePage.getByTitle('Tutup penulis pesan').click();
    await composePage.locator('.au-mail-row').first().click();
    await composePage.getByRole('button', { name: 'Teruskan' }).click();
    assert.match(await composePage.locator('.au-compose-body').inputValue(), /Sent body/);
    await composePage.close();
    const uncertain = await browser.newPage();
    await uncertain.route('**/api/**', route => {
      const url = new URL(route.request().url());
      if (url.pathname === '/api/accounts') return route.fulfill({ json: [account] });
      if (url.pathname.startsWith('/api/inbox/')) return route.fulfill({ json: { messages: [mail], errors: [], next_cursors: {}, limited_accounts: [] } });
      if (url.pathname === '/api/compose/google-account') return route.fulfill({ status: 504, body: 'synthetic timeout' });
      throw Error('Unexpected API call: ' + url.pathname);
    });
    await uncertain.goto('http://127.0.0.1:4175');
    await uncertain.getByRole('button', { name: /Tulis email/ }).click();
    await uncertain.getByRole('textbox', { name: 'Kepada', exact: true }).fill('friend@example.test');
    await uncertain.getByRole('textbox', { name: 'Subjek', exact: true }).fill('Timeout test');
    uncertain.once('dialog', dialog => dialog.accept());
    await uncertain.getByRole('button', { name: 'Kirim', exact: true }).click();
    await uncertain.getByRole('alert').filter({hasText:/Periksa folder Terkirim/}).waitFor();
    assert.equal(await uncertain.getByRole('button', { name: 'Kirim', exact: true }).isDisabled(), true);
    await uncertain.close();
    const rejected = await browser.newPage();
    let rejectedCalls = 0;
    await rejected.route('**/api/**', route => {
      const url = new URL(route.request().url());
      if (url.pathname === '/api/accounts') return route.fulfill({ json: [account] });
      if (url.pathname.startsWith('/api/inbox/')) return route.fulfill({ json: { messages: [mail], errors: [], next_cursors: {}, limited_accounts: [] } });
      if (url.pathname === '/api/compose/google-account') return route.fulfill(++rejectedCalls === 1 ? { status: 400, body: 'Alamat tidak valid' } : { status: 201, json: { id: 'fictional-id' } });
      throw Error('Unexpected API call: ' + url.pathname);
    });
    await rejected.goto('http://127.0.0.1:4175');
    await rejected.getByRole('button', { name: /Tulis email/ }).click();
    await rejected.getByRole('textbox', { name: 'Kepada', exact: true }).fill('friend@example.test');
    await rejected.getByRole('textbox', { name: 'Subjek', exact: true }).fill('Retry validation');
    rejected.on('dialog', dialog => dialog.accept());
    await rejected.getByRole('button', { name: 'Kirim', exact: true }).click();
    await rejected.getByText(/Alamat tidak valid/).waitFor();
    assert.equal(await rejected.getByRole('button', { name: 'Kirim', exact: true }).isEnabled(), true);
    await rejected.getByRole('textbox', { name: 'Subjek', exact: true }).fill('Corrected subject');
    await rejected.getByRole('button', { name: 'Kirim', exact: true }).click();
    assert.equal(rejectedCalls, 2);
    await rejected.close();
    const restored = await browser.newPage();
    let accountReads = 0;
    await restored.route('**/api/**', route => {
      const url = new URL(route.request().url());
      if (url.pathname === '/api/accounts') return route.fulfill({ json: [{ ...account, gmail_modify: ++accountReads > 1 ? true : null }] });
      if (url.pathname.startsWith('/api/inbox/')) return route.fulfill({ json: { messages: [mail], errors: [], next_cursors: {}, limited_accounts: [] } });
      if (url.pathname.startsWith('/api/message/')) return route.fulfill({ json: { sender: mail.sender, recipient: mail.recipient, subject: mail.subject, received: mail.received, body: 'Sent body', url: '' } });
      throw Error('Unexpected API call: ' + url.pathname);
    });
    await restored.goto('http://127.0.0.1:4175');
    await restored.locator('.au-mail-row').first().click();
    await restored.getByTitle('Beri bintang').waitFor();
    assert.equal(accountReads, 2);
    await restored.close();
    console.log('Verified Gmail star/archive and refreshed capability UI');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
